"""Templates and what they render to: a compose file and an .env next to it, in <servers_dir>/<folder>/<slug>/.

Everything here is pure (no Docker, no file system besides reading the templates), so it is what the tests cover.
Values only ever reach the environment of the generated service: a request names template variables, never
compose keys, and every value is checked against its variable before it is written.
"""
import hashlib
import math
import posixpath
import re
import secrets
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Optional

import yaml

from gamefleet_backend.db.models.host_settings import HostSettingsBase
from gamefleet_backend.models.template import CreateRequest, Template, TemplateVariable

TEMPLATE_DIR = Path(__file__).resolve().parent.parent / "templates"
SLUG = re.compile(r"^[a-z0-9](?:[a-z0-9-]{0,30}[a-z0-9])?$")
TAG = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$")
MEMORY = re.compile(r"^([0-9]+)([MG])$", re.I)
BOOLEAN = ("true", "false")
HEADER = """\
# Created by GameFleet from the "{template}" template. Edit freely: GameFleet notices hand edits and then
# leaves this file alone. Secrets such as the RCON password are in .env next to it.
"""
ENV_HEADER = "# Secrets for docker-compose.yml, generated by GameFleet. Keep this file private.\n"


class TemplateError(ValueError):
    """A template or a create request that cannot be used; the message is shown to the user."""


@cache
def templates() -> dict[str, Template]:
    found: dict[str, Template] = {}
    for path in sorted(TEMPLATE_DIR.glob("*.yaml")):
        template = Template.model_validate(yaml.safe_load(path.read_text()))
        if template.id in found:
            raise TemplateError(f"Template id {template.id} is used twice ({path.name})")
        for name in template.extra_volumes:
            if name == "data" or not SLUG.match(name):
                raise TemplateError(f"{template.id}: {name} is not a usable folder name")
        envs = {v.env for v in template.variables}
        for variable in template.variables:
            if unknown := set(variable.show_if) - envs:
                raise TemplateError(f"{template.id}: {variable.env} depends on unknown {', '.join(unknown)}")
        found[template.id] = template
    return found


def get_template(template_id: str) -> Template:
    try:
        return templates()[template_id]
    except KeyError:
        raise TemplateError(f"Unknown template {template_id}")


def default_value(variable: TemplateVariable, settings: HostSettingsBase) -> str:
    if variable.type == "memory" and variable.default is None:
        return f"{settings.default_memory_gb}G"
    return variable.default or ""


def active_variables(template: Template, values: dict[str, str], settings: HostSettingsBase) -> list[TemplateVariable]:
    """The variables that apply to these values: show_if conditions are met (by the value or its default)."""
    current = {v.env: values.get(v.env, default_value(v, settings)) for v in template.variables}
    return [v for v in template.variables if all(current.get(env) in allowed for env, allowed in v.show_if.items())]


def check_value(variable: TemplateVariable, value: str) -> str:
    """The value as it is written, or TemplateError."""
    if "\n" in value or "\r" in value:
        raise TemplateError(f"{variable.label} must be a single line")
    match variable.type:
        case "select":
            if value not in [o.value for o in variable.options]:
                raise TemplateError(f"{variable.label}: {value} is not one of the choices")
        case "number":
            if not re.fullmatch(r"-?[0-9]+", value):
                raise TemplateError(f"{variable.label} must be a whole number")
        case "boolean":
            value = value.lower()
            if value not in BOOLEAN:
                raise TemplateError(f"{variable.label} must be true or false")
        case "memory":
            if not MEMORY.match(value):
                raise TemplateError(f"{variable.label} must look like 6G or 512M")
            value = value.upper()
    if variable.pattern and not re.fullmatch(variable.pattern, value):
        raise TemplateError(f"{variable.label}: {value} is not valid here")
    return value


def memory_mib(value: str) -> int:
    amount, unit = MEMORY.match(value).groups()
    return int(amount) * (1024 if unit.upper() == "G" else 1)


@dataclass
class Rendered:
    folder: str  # on the host
    project: str
    container_name: str
    compose: str
    env_file: str
    secrets: list[str]
    ports: list[tuple[int, int, str]]  # (host, container, protocol) of the published ports
    image: str  # repository:tag
    volume_dirs: list[str]  # folders next to the compose file that are bound into the container

    @property
    def compose_hash(self) -> str:
        return hash_text(self.compose)


def hash_text(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def server_folder(settings: HostSettingsBase, template: Template, slug: str) -> str:
    return posixpath.join(settings.servers_dir or "/", template.folder, slug)


def render(template: Template, request: CreateRequest, settings: HostSettingsBase,
           generated: Optional[dict[str, str]] = None) -> Rendered:
    """The compose file and .env for a request. `generated` fixes the secrets (otherwise new random ones), so a
    preview and the creation that follows it can show the same file."""
    if not SLUG.match(request.slug):
        raise TemplateError("The folder name may use a-z, 0-9 and -, starting and ending with a letter or digit "
                            "(at most 32 characters)")
    if template.eula and not request.eula:
        raise TemplateError(f"Accept the EULA first: {template.eula.url}")
    tag = request.tag or template.tags[0].tag
    if not TAG.match(tag):
        raise TemplateError(f"{tag} is not a valid image tag")

    environment: dict[str, str] = dict(template.environment)
    if template.eula:
        environment[template.eula.env] = template.eula.value
    for env, key in template.settings_env.items():
        environment[env] = str(getattr(settings, key))

    env_file: dict[str, str] = {}
    memory: Optional[str] = None
    for variable in active_variables(template, request.values, settings):
        default = default_value(variable, settings)
        if variable.type == "secret":
            value = request.values.get(variable.env, "").strip() or (generated or {}).get(variable.env)
            if not value:
                if variable.required:  # one the players need, such as a join password: the user picks it
                    raise TemplateError(f"{variable.label} is required")
                value = secrets.token_urlsafe(18)
            if not re.fullmatch(r"[A-Za-z0-9_.~-]{5,128}", value):
                raise TemplateError(f"{variable.label} needs 5 to 128 letters, digits or _.~-")
            env_file[variable.env] = value
            environment[variable.env] = "${" + variable.env + "}"
            continue
        value = request.values.get(variable.env, default).strip()
        if not value:
            if variable.required:
                raise TemplateError(f"{variable.label} is required")
            continue
        value = check_value(variable, value)
        if variable.advanced and value == default:
            continue  # the image's own default; keeps the file short
        environment[variable.env] = value.replace("$", "$$")  # compose would interpolate a $
        if variable.type == "memory":
            memory = value

    shift = request.port - template.ports[0].port if request.port else 0
    if shift and template.port_env:
        environment[template.port_env] = str(request.port)
    ports: list[tuple[int, int, str]] = []
    for index, port in enumerate(template.ports):
        moves = bool(shift) and (index == 0 or port.follows)
        host = port.port + shift if moves else port.port
        if not 1 <= host <= 65535:
            raise TemplateError(f"The {port.name} port would be {host}, outside 1 to 65535")
        if port.publish:
            ports.append((host, host if moves and template.port_env else port.port, port.protocol))
    if len({(h, p) for h, _, p in ports}) != len(ports):
        raise TemplateError("Two ports of this server would use the same host port")

    project = f"{template.folder}-{request.slug}"
    service: dict = {
        "image": f"{template.image}:{tag}",
        "container_name": project,
        "restart": settings.restart_policy,
        "stop_grace_period": f"{max(settings.stop_grace_seconds, template.stop_grace)}s",
    }
    if template.tty:
        service["tty"] = True
    if template.stdin_open:
        service["stdin_open"] = True
    service["environment"] = environment
    service["ports"] = [f"{h}:{c}" + ("/udp" if p == "udp" else "") for h, c, p in ports]
    service["volumes"] = [f"./data:{template.data_path}"] + [f"./{d}:{p}" for d, p in template.extra_volumes.items()]
    limits: dict[str, str] = {}
    if memory:
        limits["memory"] = f"{math.ceil(memory_mib(memory) * (1 + template.memory_overhead))}M"
    if settings.cpu_limit:
        limits["cpus"] = f"{settings.cpu_limit:g}"
    if limits:
        service["deploy"] = {"resources": {"limits": limits}}
    service["labels"] = {"gamefleet.template": template.id}

    document = {"name": project, "services": {template.folder: service}}
    compose = HEADER.format(template=template.id) + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=120)
    env_text = ENV_HEADER + "".join(f"{k}={v}\n" for k, v in env_file.items())
    return Rendered(
        folder=server_folder(settings, template, request.slug), project=project, container_name=project,
        compose=compose, env_file=env_text, secrets=list(env_file), ports=ports, image=service["image"],
        volume_dirs=["data", *template.extra_volumes],
    )
